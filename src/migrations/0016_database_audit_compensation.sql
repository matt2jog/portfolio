		CREATE FUNCTION %1$I.suppress_redundant_updates_trigger()
		RETURNS trigger
		LANGUAGE plpgsql
		SECURITY DEFINER
		SET search_path = pg_catalog
		SET TimeZone = 'UTC'
		AS $function$
		DECLARE
			audit_identifier uuid := pg_catalog.gen_random_uuid();
			sequence_identifier bigint;
			transaction_identifier text := pg_catalog.pg_current_xact_id()::text;
			occurred timestamp with time zone := pg_catalog.clock_timestamp();
