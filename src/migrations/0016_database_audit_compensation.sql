			new_value jsonb := CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE pg_catalog.to_jsonb(NEW) END;
			source_value jsonb := CASE WHEN TG_OP = 'DELETE' THEN pg_catalog.to_jsonb(OLD) ELSE pg_catalog.to_jsonb(NEW) END;
			key_value jsonb := '{}'::jsonb;
			changed text[];
			before_value jsonb;
			after_value jsonb;
			before_redacted_value jsonb;
			after_redacted_value jsonb;
			before_hash text;
			after_hash text;
			prior_hash text;
			calculated_hash text;
			argument_index integer;
			audit_request_id text := NULLIF(pg_catalog.current_setting('portfolio_audit.request_id', true), '');
			audit_trace_id text := NULLIF(pg_catalog.current_setting('portfolio_audit.trace_id', true), '');
			audit_actor_kind text := NULLIF(pg_catalog.current_setting('portfolio_audit.actor_kind', true), '');
			audit_actor_id text := NULLIF(pg_catalog.current_setting('portfolio_audit.actor_id', true), '');
			audit_operation text := NULLIF(pg_catalog.current_setting('portfolio_audit.operation', true), '');
			audit_correlation_id text := NULLIF(pg_catalog.current_setting('portfolio_audit.correlation_id', true), '');
			audit_causation_id text := NULLIF(pg_catalog.current_setting('portfolio_audit.causation_id', true), '');
			audit_release_id text := NULLIF(pg_catalog.current_setting('portfolio_audit.release_id', true), '');
			audit_assertion_digest text := NULLIF(pg_catalog.current_setting('portfolio_audit.authentication_assertion_digest', true), '');
			compensated_audit_id uuid;
			audit_mode text;
		BEGIN
			IF pg_catalog.lower(COALESCE(
				pg_catalog.current_setting('portfolio_audit.event_silent', true),
				'off'
			)) IN ('1', 'on', 'true')
				AND session_user = 'portfolio_migrator_login'
				AND pg_catalog.current_setting('role') = 'portfolio_migrator'
			THEN
				RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
			END IF;

			IF (
				audit_request_id IS NULL
				OR audit_trace_id IS NULL
				OR audit_actor_kind IS NULL
				OR audit_actor_id IS NULL
				OR audit_operation IS NULL
				OR audit_release_id IS NULL
			) THEN
				SELECT activation.mode
				INTO STRICT audit_mode
				FROM %1$I.database_audit_activation AS activation
				WHERE activation.singleton;
				IF audit_mode = 'compatibility' THEN
					audit_request_id := 'compatibility:' || transaction_identifier;
					audit_trace_id := 'compatibility:' || transaction_identifier;
					audit_actor_kind := 'legacy-database-session';
					audit_actor_id := pg_catalog.left(session_user, 160);
					audit_operation := 'compatibility-' || pg_catalog.lower(TG_OP);
					audit_correlation_id := NULL;
					audit_causation_id := NULL;
					audit_release_id := 'pre-audit-37abdbd7a15f';
					audit_assertion_digest := NULL;
				ELSE
					RAISE EXCEPTION USING
						ERRCODE = 'PDA01',
						MESSAGE = 'Portfolio mutation audit context is required';
				END IF;
			END IF;

			IF audit_assertion_digest IS NOT NULL
				AND audit_assertion_digest !~ '^[0-9a-f]{64}$'
			THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA01',
					MESSAGE = 'Portfolio mutation authentication assertion digest is invalid';
			END IF;

			IF session_user = 'portfolio_migrator_login'
				AND pg_catalog.current_setting('role') = 'portfolio_migrator'
				AND NULLIF(
					pg_catalog.current_setting('portfolio_audit.compensation_of', true),
					''
				) IS NOT NULL
			THEN
				BEGIN
					compensated_audit_id := pg_catalog.current_setting(
						'portfolio_audit.compensation_of',
						true
					)::uuid;
				EXCEPTION WHEN invalid_text_representation THEN
					RAISE EXCEPTION USING
						ERRCODE = 'PDA01',
						MESSAGE = 'Portfolio compensation context is invalid';
				END;
			END IF;

			IF TG_NARGS < 1 THEN
				RAISE EXCEPTION 'database mutation audit trigger requires primary-key columns';
			END IF;
			FOR argument_index IN 0..TG_NARGS - 1 LOOP
				IF NOT source_value ? TG_ARGV[argument_index] THEN
					RAISE EXCEPTION 'database mutation audit key column is absent';
				END IF;
				key_value := key_value || pg_catalog.jsonb_build_object(
					TG_ARGV[argument_index],
					source_value -> TG_ARGV[argument_index]
				);
			END LOOP;

			IF TG_OP = 'UPDATE' THEN
				SELECT COALESCE(pg_catalog.array_agg(keys.key ORDER BY keys.key), '{}'::text[])
				INTO changed
				FROM (
					SELECT old_keys.key
					FROM pg_catalog.jsonb_object_keys(old_value) AS old_keys(key)
					UNION
					SELECT new_keys.key
					FROM pg_catalog.jsonb_object_keys(new_value) AS new_keys(key)
				) AS keys
				WHERE old_value -> keys.key IS DISTINCT FROM new_value -> keys.key;

				IF pg_catalog.cardinality(changed) = 0 THEN
					RETURN NEW;
				END IF;

				SELECT pg_catalog.jsonb_object_agg(columns.column_name, old_value -> columns.column_name ORDER BY columns.column_name)
				INTO before_value
				FROM pg_catalog.unnest(changed) AS columns(column_name);
				SELECT pg_catalog.jsonb_object_agg(columns.column_name, new_value -> columns.column_name ORDER BY columns.column_name)
				INTO after_value
				FROM pg_catalog.unnest(changed) AS columns(column_name);
			ELSIF TG_OP = 'INSERT' THEN
				SELECT pg_catalog.array_agg(keys.key ORDER BY keys.key)
				INTO changed
				FROM pg_catalog.jsonb_object_keys(new_value) AS keys(key);
				before_value := NULL;
				after_value := new_value;
			ELSE
				SELECT pg_catalog.array_agg(keys.key ORDER BY keys.key)
				INTO changed
				FROM pg_catalog.jsonb_object_keys(old_value) AS keys(key);
				before_value := old_value;
				after_value := NULL;
			END IF;

			before_hash := pg_catalog.encode(
				pg_catalog.sha256(pg_catalog.convert_to(COALESCE(before_value::text, 'null'), 'UTF8')),
				'hex'
			);
			after_hash := pg_catalog.encode(
				pg_catalog.sha256(pg_catalog.convert_to(COALESCE(after_value::text, 'null'), 'UTF8')),
				'hex'
			);
			before_redacted_value := CASE WHEN before_value IS NULL THEN NULL ELSE
				pg_catalog.jsonb_build_object(
					'rowKey', key_value,
					'fields', pg_catalog.to_jsonb(changed)
				)
			END;
			after_redacted_value := CASE WHEN after_value IS NULL THEN NULL ELSE
				pg_catalog.jsonb_build_object(
					'rowKey', key_value,
					'fields', pg_catalog.to_jsonb(changed)
				)
			END;

			SELECT head_hash
			INTO prior_hash
			FROM %1$I.database_audit_chain_heads
			WHERE chain_name = 'portfolio'
			FOR UPDATE;
			IF prior_hash IS NULL THEN
				RAISE EXCEPTION 'Portfolio database audit chain head is missing';
			END IF;

			SELECT pg_catalog.nextval(
				pg_catalog.pg_get_serial_sequence('%1$I.database_mutation_audit', 'sequence_number')::regclass
			)
			INTO sequence_identifier;

			calculated_hash := pg_catalog.encode(
				pg_catalog.sha256(pg_catalog.convert_to(pg_catalog.jsonb_build_object(
					'previousHash', prior_hash,
					'auditId', audit_identifier::text,
					'sequenceNumber', sequence_identifier,
					'transactionId', transaction_identifier,
					'schemaName', TG_TABLE_SCHEMA,
					'tableName', TG_TABLE_NAME,
					'operation', TG_OP,
					'rowKey', key_value,
					'changedColumns', pg_catalog.to_jsonb(changed),
					'beforeDigest', before_hash,
					'afterDigest', after_hash,
					'databaseSessionUser', session_user::text,
					'databaseCurrentUser', pg_catalog.current_setting('role'),
					'requestId', audit_request_id,
					'traceId', audit_trace_id,
					'actorKind', audit_actor_kind,
					'actorId', audit_actor_id,
					'operationContext', audit_operation,
					'correlationId', audit_correlation_id,
					'causationId', audit_causation_id,
					'releaseId', audit_release_id,
					'authenticationAssertionDigest', audit_assertion_digest,
					'compensationOf', compensated_audit_id,
					'occurredAt', pg_catalog.to_char(
						occurred AT TIME ZONE 'UTC',
						'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'
					)
				)::text, 'UTF8')),
				'hex'
			);

			INSERT INTO %1$I.database_mutation_audit (
				audit_id,
				sequence_number,
				transaction_id,
				schema_name,
				table_name,
				operation,
				row_key,
				changed_columns,
				before_redacted,
				after_redacted,
				before_digest,
				after_digest,
				database_session_user,
				database_current_user,
				request_id,
				trace_id,
				actor_kind,
				actor_id,
				operation_context,
				correlation_id,
				causation_id,
				release_id,
				authentication_assertion_digest,
				compensation_of,
				previous_hash,
				entry_hash,
				occurred_at
			) VALUES (
				audit_identifier,
				sequence_identifier,
				transaction_identifier,
				TG_TABLE_SCHEMA,
				TG_TABLE_NAME,
				TG_OP,
				key_value,
				changed,
				before_redacted_value,
				after_redacted_value,
				before_hash,
				after_hash,
				session_user::text,
				pg_catalog.current_setting('role'),
				audit_request_id,
				audit_trace_id,
				audit_actor_kind,
				audit_actor_id,
				audit_operation,
				audit_correlation_id,
				audit_causation_id,
				audit_release_id,
				audit_assertion_digest,
				compensated_audit_id,
				prior_hash,
				calculated_hash,
				occurred
			);

			DELETE FROM %1$I.database_compensation_payloads
			WHERE expires_at <= occurred;
			INSERT INTO %1$I.database_compensation_payloads (
				audit_id,
				before_state,
				after_state,
				created_at,
				expires_at
			) VALUES (
				audit_identifier,
				before_value,
				after_value,
				occurred,
				occurred + interval '7 days'
			);

			UPDATE %1$I.database_audit_chain_heads
			SET
				head_hash = calculated_hash,
				entry_count = entry_count + 1,
				updated_at = occurred
			WHERE chain_name = 'portfolio';

			RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
		END
		$function$
	$ddl$, target_schema);

