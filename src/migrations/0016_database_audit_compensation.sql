					target.schema_name,
					target.table_name,
					set_clause,
					target.schema_name,
					target.table_name
				) USING rollback_payload.before_state, target.row_key;
			END IF;

			GET DIAGNOSTICS affected_rows = ROW_COUNT;
			IF affected_rows <> 1 THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA05',
					MESSAGE = 'database compensation did not mutate exactly one row';
			END IF;

