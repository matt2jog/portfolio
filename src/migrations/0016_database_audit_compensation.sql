	EXECUTE pg_catalog.format($ddl$
		CREATE FUNCTION %1$I.compensate_database_mutation(
			requested_audit_id uuid,
			expected_current_digest text
		)
		RETURNS uuid
		LANGUAGE plpgsql
		SECURITY DEFINER
		SET search_path = pg_catalog
		SET TimeZone = 'UTC'
		AS $function$
		DECLARE
			target %1$I.database_mutation_audit%%ROWTYPE;
			rollback_payload %1$I.database_compensation_payloads%%ROWTYPE;
			current_value jsonb;
			current_projection jsonb;
			calculated_current_digest text;
			set_clause text;
			affected_rows integer;
			compensation_audit_id uuid;
			compensation_request_id text := 'compensation:' || pg_catalog.gen_random_uuid()::text;
		BEGIN
			IF session_user <> 'portfolio_migrator_login'
				OR current_user <> 'portfolio_compensation_operator' THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA04',
					MESSAGE = 'database compensation requires the dedicated Portfolio compensation boundary';
			END IF;
			IF pg_catalog.lower(COALESCE(
				pg_catalog.current_setting('portfolio_audit.event_silent', true),
				'off'
			)) IN ('1', 'on', 'true') THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA04',
					MESSAGE = 'database compensation cannot run event-silent';
			END IF;

			SELECT *
			INTO target
			FROM %1$I.database_mutation_audit
			WHERE audit_id = requested_audit_id;
			IF NOT FOUND THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA01',
					MESSAGE = 'database compensation audit target does not exist';
			END IF;
			IF expected_current_digest !~ '^[0-9a-f]{64}$'
				OR expected_current_digest <> target.after_digest
			THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA01',
					MESSAGE = 'database compensation expected digest does not match the audited after-state';
			END IF;
			SELECT payload.*
			INTO rollback_payload
			FROM %1$I.database_compensation_payloads AS payload
			WHERE payload.audit_id = target.audit_id
				AND payload.expires_at > pg_catalog.clock_timestamp();
			IF NOT FOUND THEN
				RAISE EXCEPTION USING
					ERRCODE = 'PDA06',
					MESSAGE = 'database compensation rollback payload is absent or expired';
			END IF;

			EXECUTE pg_catalog.format(
				'SELECT pg_catalog.to_jsonb(candidate) FROM %%I.%%I AS candidate WHERE pg_catalog.to_jsonb(candidate) @> $1 FOR UPDATE',
				target.schema_name,
				target.table_name
			)
			INTO current_value
			USING target.row_key;

			IF current_value IS NULL THEN
				current_projection := NULL;
			ELSIF target.operation = 'UPDATE' THEN
				SELECT pg_catalog.jsonb_object_agg(
					columns.column_name,
					current_value -> columns.column_name
					ORDER BY columns.column_name
				)
				INTO current_projection
